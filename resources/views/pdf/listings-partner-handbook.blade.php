    <h3>Step by step</h3>
    <ol class="steps">
        <li>In "Data Enrichment", sort or filter by completion score to find the lowest-scoring listings first.</li>
        <li>Click a row to open it — it opens in tabs: Basic, Contact, Address, Description, Photos, Metadata.</li>
        <li>Research the business and fill in whatever tab matches what you found — you don't have to do every tab in one sitting.</li>
        <li>Write the description in your own words — don't copy-paste text wholesale from their website.</li>
        <li>Save. The completion score updates automatically.</li>
    </ol>

    <div class="box"><strong>Photo rights — please don't skip this:</strong> only use a photo if the business itself published it (their own site or official social page), or if you have their explicit OK. Never pull from Google Images, TripAdvisor reviews, or other travelers' posts. If in doubt, leave the photo blank rather than guess.</div>

    <p><strong>Definition of "done":</strong> a listing is in good shape once its score is 90% or higher. Some fields (like "activities on offer") genuinely don't apply to every place.</p>

    <h2>3. Job 2 — Contact the owners</h2>
    <p>Most of these businesses don't know they're listed on NamibWay yet. We want to let them know, invite them to claim their own page, and — where they use a booking system — get that connected.</p>

    <h3>3.1 — Send the claim invite</h3>
    <ol class="steps">
        <li>Once a listing has a working email address on file, open its Partner record and use the "Invite Owner" action.</li>
        <li>This sends an email with a personal link letting them log in (no password needed) and edit their own page.</li>
        <li>The system tracks who's been invited, replied, or declined — all visible on the Partner list.</li>
    </ol>

    <h3>3.2 — No email on file yet?</h3>
    <p>This is likely the bulk of the outreach work. Find a contact channel first (website contact form, listed phone number, Facebook page) — then either email them the claim link, or call and offer to fill in confirmed details yourself if they're not comfortable online.</p>

    <h3>3.3 — Following up</h3>
    <p>For accommodation, activity operators and vehicle rental companies especially, a follow-up call 5–7 days later is worth it — these matter most to trip quality. For restaurants, one email is usually enough.</p>

    <div class="box"><strong>If a partner asks about money, contracts, or commission terms:</strong> don't negotiate or promise anything — note what they asked and pass it to Adriano or Till. Your role is data and relationships, not deal terms.</div>

    <h3>3.4 — Booking systems (if mentioned)</h3>
    <p>If an owner uses ResRequest, NightsBridge, hopeCloud, Wetu, or Namibia Wildlife Resorts' system, note which one on their Partner record ("Connector Type" field). No need to configure API access yourself — that's a separate technical step. No system at all is completely normal for smaller operators — mark it "Manual".</p>

