    <h2>1. Getting started</h2>
    <p>NamibWay is an AI travel-planning site for Namibia. Travelers chat with "Kaia," our AI trip assistant, and get a bookable day-by-day itinerary — pulled together from real accommodation, activities, restaurants and vehicle rentals in our database. Your work directly improves what Kaia can recommend.</p>
    <p>You have your own login to the admin area — a username/email and a temporary password, sent separately. Please don't share this login with anyone or reuse Adriano's account; each person needs their own so we can tell whose changes are whose, and so we can turn off access cleanly if your role ever changes.</p>
    <p><strong>Admin dashboard</strong> — <span class="mono">namibway.com/admin</span>, your own login (above). Where you'll do the work in Sections 2–4.</p>
    <p><strong>Team webmail</strong> (for emailing partners, customers &amp; businesses directly) — <span class="mono">webmail.namibway.com</span>, log in as <span class="mono">team@namibway.com</span>; the password will be shared with you separately. Use this for any direct correspondence — replies, manual outreach, follow-ups — that isn't sent automatically by the "Invite Owner" action.</p>
    <div class="box good"><strong>First 10 minutes:</strong> click "Data Enrichment" in the left-hand menu. You'll land on a table of every listing with a completion score. That table and the stat tiles above it are your dashboard for everything in Section 2.</div>

    <h2>2. Job 1 — Complete a listing profile</h2>
    <p>Every listing (a lodge, tour, restaurant, or rental vehicle) has a completion score out of 100. Your job is to raise it by filling in what's missing — using the business's own website, Google, Facebook, TripAdvisor, or a phone call when nothing is online.</p>

